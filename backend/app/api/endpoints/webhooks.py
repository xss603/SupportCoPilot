import hmac
from typing import Optional
from fastapi import APIRouter, BackgroundTasks, Depends, Header, HTTPException, Request, status
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession
from app.core.config import settings
from app.db.session import async_session_factory, get_db
from app.models.entities import AuditLog, Issue
from app.schemas.gitlab_webhook import WebhookResponse
from app.services.triage_service import triage_service

router = APIRouter(prefix="/webhooks", tags=["Webhooks"])


async def run_async_triage(issue_id):
    """Background task to run triage asynchronously without blocking the webhook response."""
    async with async_session_factory() as db:
        stmt = select(Issue).where(Issue.id == issue_id)
        res = await db.execute(stmt)
        issue = res.scalar_one_or_none()
        if issue:
            try:
                await triage_service.triage_issue(db, issue)
            except Exception as e:
                print(f"Error during async triage for issue {issue_id}: {e}")


@router.post("/gitlab", response_model=WebhookResponse, status_code=status.HTTP_202_ACCEPTED)
async def gitlab_webhook_listener(
    request: Request,
    background_tasks: BackgroundTasks,
    x_gitlab_token: Optional[str] = Header(None, alias="X-Gitlab-Token"),
    x_gitlab_event: Optional[str] = Header(None, alias="X-Gitlab-Event"),
    x_gitlab_event_uuid: Optional[str] = Header(None, alias="X-Gitlab-Event-UUID"),
    db: AsyncSession = Depends(get_db),
):
    """
    Receives incoming GitLab Issue & Note webhook events, validates X-Gitlab-Token
    in constant time, enforces idempotency, upserts issues/notes, and queues async triage.
    """
    expected_secret = settings.GITLAB_WEBHOOK_SECRET or ""
    if not expected_secret or expected_secret == "your-webhook-secret":
        if not settings.DEBUG:
            raise HTTPException(
                status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                detail="Webhook secret is not configured",
            )
    else:
        if not x_gitlab_token or not hmac.compare_digest(
            x_gitlab_token.encode("utf-8"),
            expected_secret.encode("utf-8"),
        ):
            raise HTTPException(
                status_code=status.HTTP_401_UNAUTHORIZED,
                detail="Invalid X-Gitlab-Token header",
            )

    payload = await request.json()
    object_kind = payload.get("object_kind")

    if object_kind not in ["issue", "note"]:
        return WebhookResponse(
            status="ignored",
            message="Unsupported webhook event kind",
            reason=f"Unsupported event kind: {object_kind}",
        )

    if object_kind == "issue":
        attrs = payload.get("object_attributes", {})
        action = attrs.get("action")

        if action not in ["open", "reopen", "update", "close"]:
            return WebhookResponse(
                status="ignored",
                message="Non-actionable issue action",
                reason=f"Non-actionable issue action: {action}",
            )

        project_id = payload.get("project", {}).get("id")
        issue_iid = attrs.get("iid")
        gitlab_id = attrs.get("id")
        title = attrs.get("title", "")
        description = attrs.get("description", "")
        state = attrs.get("state", "opened")
        web_url = attrs.get("url", "")
        author = payload.get("user", {})

        if author.get("username") == settings.GITLAB_BOT_USERNAME:
            return WebhookResponse(
                status="ignored",
                message="Bot-authored event ignored",
                reason="Event generated by support bot",
            )

        raw_labels = payload.get("labels", [])
        labels = [l.get("title") if isinstance(l, dict) else str(l) for l in raw_labels]

        if action in ["open", "reopen"] and any(l.lower() == "ai-triaged" for l in labels):
            return WebhookResponse(
                status="ignored",
                message="Already triaged",
                reason="Issue already carries ai-triaged label",
            )

        stmt = select(Issue).where(Issue.project_id == project_id, Issue.iid == issue_iid)
        res = await db.execute(stmt)
        existing_issue = res.scalar_one_or_none()

        if existing_issue:
            existing_issue.title = title
            existing_issue.description = description
            existing_issue.state = state
            existing_issue.labels = labels
            target_issue = existing_issue
        else:
            target_issue = Issue(
                gitlab_id=gitlab_id,
                project_id=project_id,
                iid=issue_iid,
                title=title,
                description=description,
                state=state,
                author_username=author.get("username", "unknown"),
                author_name=author.get("name"),
                author_avatar_url=author.get("avatar_url"),
                labels=labels,
                web_url=web_url,
                status="ingested",
            )
            db.add(target_issue)

        await db.commit()
        await db.refresh(target_issue)

        audit = AuditLog(
            entity_type="issue",
            entity_id=str(target_issue.id),
            actor=f"user:{author.get('username', 'unknown')}",
            event="webhook_received",
            details={
                "project_id": project_id,
                "iid": issue_iid,
                "title": title,
                "event_uuid": x_gitlab_event_uuid,
                "gitlab_event": x_gitlab_event,
            },
        )
        db.add(audit)
        await db.commit()

        background_tasks.add_task(run_async_triage, target_issue.id)

        return WebhookResponse(
            status="accepted",
            message="Webhook received and queued for AI triage",
            issue_id=str(target_issue.id),
            iid=issue_iid,
        )

    return WebhookResponse(
        status="accepted",
        message="Note webhook accepted for M2 processing",
    )
